// Reuse the game's SVG poses as PNGs readable by the iOS widget.
// SHARP_MODULE=/path/to/sharp node scripts/generate-widget-art.cjs
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const ts = require('typescript');
const sharp = require(process.env.SHARP_MODULE || 'sharp');
const root = path.resolve(__dirname, '..');
const cache = new Map();
function load(file) {
  if (cache.has(file)) return cache.get(file);
  const module = { exports: {} }; cache.set(file, module.exports);
  const code = ts.transpileModule(fs.readFileSync(file, 'utf8'), {
    compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 },
  }).outputText;
  vm.runInNewContext(code, { module, exports: module.exports, require: name => {
    const target = name.startsWith('@/') ? path.join(root, 'src', name.slice(2)) : path.resolve(path.dirname(file), name);
    return load(target + '.ts');
  } }, { filename: file });
  return module.exports;
}
(async () => {
  const { petSprites, APPEARANCES } = load(path.join(root, 'src/components/pet-sprite-art.ts'));
  const out = path.join(root, 'assets/widgets'); fs.mkdirSync(out, { recursive: true });
  const imports = [];
  for (const appearance of Object.keys(APPEARANCES)) for (let stage = 0; stage < 7; stage++) {
    const poses = petSprites(appearance, stage);
    for (const state of ['awake', 'asleep']) {
      const name = `${appearance}-${stage}-${state}`;
      const svg = Buffer.from(poses[state][0].uri.split(',')[1], 'base64');
      await sharp(svg).trim().resize(240, 240, { fit: 'contain', kernel: 'nearest', background: '#00000000' })
        .extend({ top: 8, bottom: 8, left: 8, right: 8, background: '#00000000' }).png().toFile(path.join(out, name + '.png'));
      imports.push(`  '${name}': require('../../assets/widgets/${name}.png'),`);
    }
  }
  fs.writeFileSync(path.join(root, 'src/widgets/art.ts'), '// Generated by scripts/generate-widget-art.cjs\nexport const widgetArt: Record<string, number> = {\n' + imports.join('\n') + '\n};\n');
  console.log(`Generated ${imports.length} widget poses from the existing game artwork.`);
})().catch(error => { console.error(error); process.exitCode = 1; });
